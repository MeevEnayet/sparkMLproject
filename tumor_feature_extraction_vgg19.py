# Create a dictionary to map patient_id to response
clinical_dict = dict(zip(clinical_data['patient_id'], clinical_data['response']))

# Function to load images
def load_images(image_folder):
    images = {}
    for filename in os.listdir(image_folder):
        if filename.endswith('.png'):
            image_name = filename[:-4]  # Remove the '.png' part
            image_path = os.path.join(image_folder, filename)
            image = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
            if image is not None:
                images[image_name] = image
            else:
                print(f"Warning: {filename} could not be read.")
    return images

# Load images
image_data = load_images(image_folder)

